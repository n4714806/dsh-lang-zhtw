// Reproducible build. Does not inspect or modify a DSH profile.
import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';
import {convertDictionary,protectedTokens} from './convert.mjs';
import assert from 'node:assert/strict';
import {buildSync} from 'esbuild';
const root = new URL('../',import.meta.url);
const json = path => JSON.parse(readFileSync(new URL(path,root),'utf8'));
export function buildDictionaries() {
  const result=json('dictionaries/host.zh-TW.json');
  for(const source of json('dictionaries/sources.json')) {
    assert.ok(!Object.hasOwn(result,source.namespace),'Duplicate namespace: '+source.namespace);
    const original=json('dictionaries/source/'+source.package+'.zh.json');
    assert.equal(Object.keys(original).length,source.keys,'Source snapshot key count drift');
    const converted=convertDictionary(original);
    validate(original,converted);
    result[source.namespace]=converted;
  }
  return result;
}
export function validate(before,after) {
  if(typeof before==='string') {assert.equal(typeof after,'string');assert.deepEqual(protectedTokens(after),protectedTokens(before),'Protected token changed');return;}
  if(before&&typeof before==='object') {assert.equal(Array.isArray(after),Array.isArray(before));assert.deepEqual(Object.keys(after),Object.keys(before));for(const key of Object.keys(before))validate(before[key],after[key]);return;}
  assert.equal(after,before);
}
let readerBundle;
export function renderClient(dictionaries) {
  readerBundle ??= buildSync({entryPoints:[fileURLToPath(new URL('src/client-features.mjs',root))],bundle:true,format:'iife',globalName:'ZhTWReader',platform:'browser',target:'es2022',minify:true,write:false,legalComments:'inline'}).outputFiles[0].text;
  return `// Generated by npm run build; edit dictionary sources or tools, not this artifact.
// Modified/translated Mnemon (MIT) and Context (Apache-2.0) dictionary data included.
// Original notices and full licenses: THIRD_PARTY_NOTICES.md and licenses/.
// UI dictionaries, selected-text reader, and explicit native composer conversion.
// Composer changes require the paired owner API and a user menu action; no DOM rewrites, submissions or history-message edits.
// Fallback: zh-TW -> zh -> en. See docs/coverage.md for source-page bypasses.
window.__ModuleLoader__.load({
  id: 'dsh-lang-zhtw',
  factory(require) {
    ${readerBundle}
    const DICTIONARIES = ${JSON.stringify(dictionaries,null,2)};
    return {
      inject: ['locale', 'slots'],
      apply(ctx) {
        ctx.effect(() => ctx.locale.addLanguage({id:'zh-TW',label:'繁體中文（台灣）',fallback:'zh'}), 'lang-zhtw: language');
        for (const [namespace,dict] of Object.entries(DICTIONARIES)) {
          ctx.effect(() => ctx.locale.register(namespace,'zh-TW',dict), 'lang-zhtw: dictionary '+namespace);
        }
        ZhTWReader.installReader(ctx, require('react'));
        ZhTWReader.installComposerConverter(ctx, require('react'));
      },
    };
  },
});
`;
}
if(process.argv[1] && resolve(process.argv[1])===fileURLToPath(import.meta.url)) {
  const dictionaries=buildDictionaries();
  writeFileSync(new URL('client.js',root),renderClient(dictionaries));
  console.log('Generated '+Object.keys(dictionaries).length+' namespaces; '+Object.values(dictionaries).reduce((n,d)=>n+Object.keys(d).length,0)+' top-level keys.');
}
